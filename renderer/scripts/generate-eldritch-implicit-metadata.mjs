import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const REPOE_MODS = 'https://repoe-fork.github.io/mods.min.json'
const TRADE_STATS = 'https://www.pathofexile.com/api/trade/data/stats'
const OUTPUT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/web/price-check/trade/eldritch-implicit-metadata.ts'
)

const GENERATION_TO_INFLUENCE = {
  searing_exarch_implicit: 'searing-exarch',
  eater_of_worlds_implicit: 'eater-of-worlds'
}

const NUMBER = '[+-]?\\d+(?:\\.\\d+)?'
const RANGE_OR_NUMBER = `\\(${NUMBER}-${NUMBER}\\)|${NUMBER}`

function normalizeForJoin (text) {
  return text
    .trim()
    .replace(/\s+/g, ' ')
    .replace(/\([+-]?\d+(?:\.\d+)?(?:-[+-]?\d+(?:\.\d+)?)?\)/g, '#')
    .replace(/\d+(?:\.\d+)?/g, '#')
    .replace(/#+/g, '#')
}

function escapeRegex (text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function tradeTemplateRegex (template) {
  const source = template
    .trim()
    .replace(/\s+/g, ' ')
    .split('#')
    .map(escapeRegex)
    .join(`(${RANGE_OR_NUMBER})`)
  return new RegExp(`^${source}$`)
}

function parseBounds (token) {
  const range = token.match(/^\(([+-]?\d+(?:\.\d+)?)-([+-]?\d+(?:\.\d+)?)\)$/)
  if (range) return [Number(range[1]), Number(range[2])]
  const value = Number(token)
  return [value, value]
}

function fingerprint (captures) {
  return captures
    .map(parseBounds)
    .map(([min, max]) => `${min},${max}`)
    .join(';')
}

function eldritchRank (mod) {
  for (const spawnWeight of mod.spawn_weights ?? []) {
    const match = spawnWeight.tag?.match(/^no_tier_(\d)_eldritch_implicit$/)
    if (match) return 7 - Number(match[1])
  }
  return undefined
}

function hasHiddenPresenceCondition (mod) {
  return (mod.stats ?? []).some(stat => stat.id?.startsWith('local_influence_mod_requires_'))
}

async function fetchJson (url) {
  const response = await fetch(url, {
    headers: { 'User-Agent': 'Krangled-PoE-Trade data generator' }
  })
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`)
  return response.json()
}

const [mods, tradeStats] = await Promise.all([
  fetchJson(REPOE_MODS),
  fetchJson(TRADE_STATS)
])

const modsByText = new Map()
for (const mod of Object.values(mods)) {
  const influence = GENERATION_TO_INFLUENCE[mod.generation_type]
  if (!influence) continue

  const key = normalizeForJoin(mod.text)
  const entries = modsByText.get(key) ?? []
  entries.push({ influence, mod })
  modsByText.set(key, entries)
}

const metadata = {}
for (const group of tradeStats.result) {
  for (const entry of group.entries) {
    if (entry.type !== 'implicit') continue

    const candidates = modsByText.get(normalizeForJoin(entry.text)) ?? []
    const influences = new Set(candidates.map(candidate => candidate.influence))
    if (influences.size !== 1) continue

    const template = tradeTemplateRegex(entry.text)
    const tiers = new Map()
    for (const { mod } of candidates) {
      // RePoE's rendered text omits these conditions, while the trade API
      // assigns them separate stat hashes. Excluding them keeps ordinary
      // implicit tier inference conservative instead of mixing mod families.
      if (hasHiddenPresenceCondition(mod)) continue

      const match = mod.text.trim().replace(/\s+/g, ' ').match(template)
      const rank = eldritchRank(mod)
      if (!match || rank == null) continue

      const key = fingerprint(match.slice(1))
      const ranks = tiers.get(key) ?? new Set()
      ranks.add(rank)
      tiers.set(key, ranks)
    }

    metadata[entry.id] = {
      influence: [...influences][0],
      tiers: Object.fromEntries(
        [...tiers.entries()]
          .sort(([a], [b]) => a.localeCompare(b))
          .map(([key, ranks]) => [key, [...ranks].sort((a, b) => a - b)])
      )
    }
  }
}

const sortedMetadata = Object.fromEntries(
  Object.entries(metadata).sort(([a], [b]) => a.localeCompare(b))
)

const source = `/* eslint-disable */
// Generated by scripts/generate-eldritch-implicit-metadata.mjs.
// Sources: RePoE PoE 1 mods and the official PoE 1 trade-stat API.
// Do not edit this file by hand.

export type EldritchImplicitInfluence = 'searing-exarch' | 'eater-of-worlds'

export interface EldritchImplicitMetadata {
  influence: EldritchImplicitInfluence
  tiers: Record<string, number[]>
}

export const ELDRITCH_IMPLICIT_METADATA: Record<string, EldritchImplicitMetadata> = ${JSON.stringify(sortedMetadata, null, 2)}
`

await fs.writeFile(OUTPUT, source)
console.log(`Wrote ${Object.keys(sortedMetadata).length} Eldritch implicit stat definitions to ${OUTPUT}`)
